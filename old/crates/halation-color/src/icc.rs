//! Minimal ICC v2.4 matrix/TRC profile writer for the export spaces (sRGB, Display P3, Adobe RGB,
//! ProPhoto). Colorants are D50-adapted (Bradford), exactly as the ICC specification requires, and
//! the profiles round-trip through [`DisplayProfile::from_icc`](crate::DisplayProfile::from_icc).

use super::{
    adobe_rgb_to_xyz_d65, bradford_cat, display_p3_to_xyz_d65, prophoto_to_xyz_d50,
    srgb_to_xyz_d65, OutputSpace, D50, D65,
};

fn s15(v: f64) -> [u8; 4] {
    ((v * 65536.0).round() as i32).to_be_bytes()
}

fn xyz_tag(x: f64, y: f64, z: f64) -> Vec<u8> {
    let mut t = b"XYZ \0\0\0\0".to_vec();
    for v in [x, y, z] {
        t.extend_from_slice(&s15(v));
    }
    t
}

fn gamma_curve(g: f64) -> Vec<u8> {
    let mut t = b"curv\0\0\0\0".to_vec();
    t.extend_from_slice(&1u32.to_be_bytes());
    t.extend_from_slice(&((g * 256.0).round() as u16).to_be_bytes());
    t.extend_from_slice(&[0, 0]);
    t
}

/// IEC 61966-2.1 transfer curve as ICC parametric type 3.
fn srgb_curve() -> Vec<u8> {
    let mut t = b"para\0\0\0\0".to_vec();
    t.extend_from_slice(&3u16.to_be_bytes());
    t.extend_from_slice(&[0, 0]);
    for v in [2.4, 1.0 / 1.055, 0.055 / 1.055, 1.0 / 12.92, 0.04045] {
        t.extend_from_slice(&s15(v));
    }
    t
}

fn text_tag(s: &str) -> Vec<u8> {
    let mut t = b"text\0\0\0\0".to_vec();
    t.extend_from_slice(s.as_bytes());
    t.push(0);
    t
}

/// ICC v2 `textDescriptionType`.
fn desc_tag(s: &str) -> Vec<u8> {
    let mut t = b"desc\0\0\0\0".to_vec();
    t.extend_from_slice(&(s.len() as u32 + 1).to_be_bytes());
    t.extend_from_slice(s.as_bytes());
    t.push(0);
    t.extend_from_slice(&[0u8; 4 + 4 + 2 + 1 + 67]); // unicode + scriptcode sections, all empty
    t
}

pub fn build_icc_profile(space: OutputSpace) -> Vec<u8> {
    let to_xyz_d50 = match space {
        OutputSpace::Srgb => bradford_cat(D65, D50) * srgb_to_xyz_d65(),
        OutputSpace::DisplayP3 => bradford_cat(D65, D50) * display_p3_to_xyz_d65(),
        OutputSpace::AdobeRgb => bradford_cat(D65, D50) * adobe_rgb_to_xyz_d65(),
        OutputSpace::ProPhoto => prophoto_to_xyz_d50(),
    };
    let curve = match space {
        OutputSpace::Srgb | OutputSpace::DisplayP3 => srgb_curve(),
        OutputSpace::AdobeRgb => gamma_curve(563.0 / 256.0),
        OutputSpace::ProPhoto => gamma_curve(1.8),
    };
    let colorant = |c: glam::DVec3| xyz_tag(c.x, c.y, c.z);
    let tags: Vec<(&[u8; 4], Vec<u8>)> = vec![
        (b"desc", desc_tag(space.name())),
        (b"cprt", text_tag("Generated by Halation; no copyright")),
        (b"wtpt", xyz_tag(D50.x, D50.y, D50.z)),
        (b"rXYZ", colorant(to_xyz_d50.x_axis)),
        (b"gXYZ", colorant(to_xyz_d50.y_axis)),
        (b"bXYZ", colorant(to_xyz_d50.z_axis)),
        (b"rTRC", curve.clone()),
        (b"gTRC", curve.clone()),
        (b"bTRC", curve),
    ];

    let mut offset = 128 + 4 + tags.len() * 12;
    let mut table = (tags.len() as u32).to_be_bytes().to_vec();
    let mut body = Vec::new();
    for (sig, data) in &tags {
        let padded = (data.len() + 3) & !3;
        table.extend_from_slice(*sig);
        table.extend_from_slice(&(offset as u32).to_be_bytes());
        table.extend_from_slice(&(data.len() as u32).to_be_bytes());
        body.extend_from_slice(data);
        body.resize(body.len() + (padded - data.len()), 0);
        offset += padded;
    }

    let mut header = vec![0u8; 128];
    header[8..12].copy_from_slice(&0x0240_0000u32.to_be_bytes()); // v2.4
    header[12..16].copy_from_slice(b"mntr");
    header[16..20].copy_from_slice(b"RGB ");
    header[20..24].copy_from_slice(b"XYZ ");
    for (i, v) in [2024u16, 1, 1, 0, 0, 0].iter().enumerate() {
        header[24 + i * 2..26 + i * 2].copy_from_slice(&v.to_be_bytes());
    }
    header[36..40].copy_from_slice(b"acsp");
    for (i, v) in [D50.x, D50.y, D50.z].iter().enumerate() {
        header[68 + i * 4..72 + i * 4].copy_from_slice(&s15(*v));
    }
    let total = (header.len() + table.len() + body.len()) as u32;
    header[0..4].copy_from_slice(&total.to_be_bytes());

    let mut out = header;
    out.extend_from_slice(&table);
    out.extend_from_slice(&body);
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{DisplayLut, DisplayProfile};

    #[test]
    fn generated_profiles_parse_and_agree_with_the_builtin_srgb() {
        for space in [
            OutputSpace::Srgb,
            OutputSpace::DisplayP3,
            OutputSpace::AdobeRgb,
            OutputSpace::ProPhoto,
        ] {
            let icc = build_icc_profile(space);
            assert_eq!(
                u32::from_be_bytes([icc[0], icc[1], icc[2], icc[3]]) as usize,
                icc.len()
            );
            let parsed =
                DisplayProfile::from_icc(&icc).unwrap_or_else(|e| panic!("{space:?}: {e}"));
            assert_eq!(parsed.description, space.name());
        }
        let generated = DisplayLut::from_icc(&build_icc_profile(OutputSpace::Srgb)).unwrap();
        let builtin = DisplayLut::srgb();
        for rgb in [[0.18f32; 3], [0.4, 0.2, 0.1]] {
            let (a, b) = (generated.apply(rgb), builtin.apply(rgb));
            assert!((0..3).all(|k| (a[k] - b[k]).abs() < 0.01), "{a:?} vs {b:?}");
        }
    }
}
